#!/bin/sh
# Regenerate every dashboard of `deploy/dashboards/` from its script in `tools/dashboards/`
# (ANR-1349). The JSON is committed and is the source of truth for a reviewer; this script is what
# CI runs, and it fails the build through `git diff --exit-code` when the committed JSON and the
# scripts disagree, so a hand-edited dashboard cannot merge.
#
# Two ways this could pass over nothing, and neither does: every committed `*.json` must have its
# `<name>.py` (an orphan dashboard is one no regeneration can repair), and at least one script must
# have run (a glob that matches nothing is not a green build).
#
# Standard library only: the scripts need `python3` and nothing else. A file whose *name* starts
# with an underscore is a helper module, not a dashboard, and is not run.
set -eu

root=$(CDPATH='' cd -- "$(dirname -- "$0")/../.." && pwd)

count=0
for script in "$root"/tools/dashboards/*.py; do
  [ -e "$script" ] || continue
  case "$(basename "$script")" in
    _*) continue ;;
  esac
  python3 "$script"
  count=$((count + 1))
done

if [ "$count" -eq 0 ]; then
  echo "no dashboard script ran: nothing was regenerated" >&2
  exit 1
fi

for dashboard in "$root"/deploy/dashboards/*.json; do
  [ -e "$dashboard" ] || continue
  name=$(basename "$dashboard" .json)
  if [ ! -f "$root/tools/dashboards/$name.py" ]; then
    echo "$(basename "$dashboard") is generated by nothing: tools/dashboards/$name.py does not exist" >&2
    exit 1
  fi
done

printf 'regenerated %s dashboard script(s), every dashboard has one\n' "$count"
