//! The operator: the composition root. `crdgen` prints the CRDs; `run` composes the
//! Kubernetes runtime provider, the store (CloudNativePG, or referenced Secrets) and the controllers, and
//! serves health (8081), metrics (9090) and, with a token, the agent registry (8080).

mod run;
#[cfg(feature = "runtime-kubernetes")]
mod serve;

use std::io::{self, Write};
use std::process::ExitCode;

use anyhow::{Context, Result};
use clap::{Parser, Subcommand};

/// The adam-rs operator.
#[derive(Debug, Parser)]
#[command(name = "adam-operator", version, about)]
struct Cli {
    #[command(subcommand)]
    command: Command,
}

// `Run` carries every setting of `run`; the enum is parsed once at start, so its size costs nothing.
#[derive(Debug, Subcommand)]
#[allow(clippy::large_enum_variant)]
enum Command {
    /// Print the CustomResourceDefinitions as multi-document YAML.
    Crdgen,
    /// Run the controllers: reconcile AgentService and AgentConfig objects.
    Run(run::RunArgs),
}

fn main() -> ExitCode {
    match real_main(Cli::parse()) {
        Ok(()) => ExitCode::SUCCESS,
        Err(err) => {
            eprintln!("adam-operator: {err:#}");
            ExitCode::FAILURE
        }
    }
}

fn real_main(cli: Cli) -> Result<()> {
    match cli.command {
        Command::Crdgen => crdgen(&mut io::stdout().lock()),
        Command::Run(args) => {
            tracing_subscriber::fmt()
                .with_env_filter(
                    tracing_subscriber::EnvFilter::try_from_default_env()
                        .unwrap_or_else(|_| tracing_subscriber::EnvFilter::new("info")),
                )
                .with_writer(io::stderr)
                .init();
            tokio::runtime::Builder::new_multi_thread()
                .enable_all()
                .build()
                .context("starting the async runtime")?
                .block_on(run::run(args))
        }
    }
}

/// Header of the generated file. `deploy/crds/agents.vymalo.com.yaml` starts with it.
const HEADER: &str = "# Generated by `cargo run -p adam-operator -- crdgen`. Do not edit.\n\
                      # CI fails when this file differs from the output of the command.\n";

/// Write the CRDs of `adam-operator-api` as one YAML document each.
fn crdgen(out: &mut impl Write) -> Result<()> {
    out.write_all(HEADER.as_bytes())?;
    for crd in adam_operator_api::crds() {
        out.write_all(b"---\n")?;
        // Through a key-sorted value: the schema's maps keep their order only with serde_json's
        // `preserve_order`, which another crate of a workspace build turns on.
        let value = serde_json::to_value(&crd).context("serialising a CRD")?;
        let yaml = serde_yaml::to_string(&sorted(&value)).context("serialising a CRD to YAML")?;
        out.write_all(yaml.as_bytes())?;
    }
    out.flush()?;
    Ok(())
}

/// The value with every object's members in key order, in any build.
fn sorted(value: &serde_json::Value) -> serde_json::Value {
    use serde_json::Value;
    match value {
        Value::Object(map) => {
            let keys: std::collections::BTreeMap<&String, &Value> = map.iter().collect();
            Value::Object(
                keys.into_iter()
                    .map(|(k, v)| (k.clone(), sorted(v)))
                    .collect(),
            )
        }
        Value::Array(items) => Value::Array(items.iter().map(sorted).collect()),
        other => other.clone(),
    }
}
